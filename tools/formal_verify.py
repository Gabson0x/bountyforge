def main():
    import argparse
    parser = argparse.ArgumentParser(
        description="BountyForge Formal Verification Bridge")
    parser.add_argument("--finding-file", help="JSONL file with findings")
    parser.add_argument("--finding-id", help="Single finding ID")
    parser.add_argument("--target", help="Target name to load findings from state")
    parser.add_argument("--generate-only", action="store_true",
                        help="Generate harnesses without running")
    parser.add_argument("--run", help="Run verification on a harness")
    parser.add_argument("--type", help="Artifact type for --run",
                        choices=["certora_spec", "fuzz_harness", "api_test"])
    parser.add_argument("--framework", default="foundry",
                        choices=["foundry", "medusa"],
                        help="Fuzzing framework (default: foundry)")
    args = parser.parse_args()

    bridge = FormalVerifyBridge()

    # Load findings
    findings = []
    if args.finding_file:
        raw = Path(args.finding_file).read_text()
        findings = [json.loads(l) for l in raw.splitlines() if l.strip()]
    elif args.target:
        try:
            from tools.state import get_findings
            findings = get_findings(args.target)
        except ImportError:
            print("[!] state module not available")
            sys.exit(1)
    elif args.finding_id:
        findings = [{"finding_id": args.finding_id, "title": "Manual"}]

    if not findings and not args.run:
        print("[!] No findings loaded")
        sys.exit(1)

    if args.run:
        result = bridge.run_verification(args.run, args.type or "fuzz_harness")
        print(json.dumps(result, indent=2))

    else:
        print(f"[*] BountyForge Formal Verification Bridge v2.1.0")
        print(f"[*] Processing {len(findings)} finding(s)...")

        results = bridge.generate_all(findings)

        print(f"\n[*] Generated:")
        print(f"    Certora specs:  {results['certora_specs']}")
        print(f"    Fuzz harnesses: {results['fuzz_harnesses']}")
        print(f"    API tests:      {results['api_tests']}")

        if results["errors"]:
            print(f"\n[!] Errors:")
            for e in results["errors"]:
                print(f"    [{e['finding_id']}] {e['error']}")

        if results["artifacts"]:
            print(f"\n[*] Artifacts:")
            for a in results["artifacts"]:
                print(f"    [{a['type']}] {a['path']}")


if __name__ == "__main__":
    main()
