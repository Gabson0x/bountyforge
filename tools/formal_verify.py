class FormalVerifyBridge:
    """Bridges findings to formal verification tools."""

    def __init__(self):
        VERIFY_DIR.mkdir(parents=True, exist_ok=True)
        (VERIFY_DIR / "certora").mkdir(exist_ok=True)
        (VERIFY_DIR / "echidna").mkdir(exist_ok=True)
        (VERIFY_DIR / "medusa").mkdir(exist_ok=True)
        (VERIFY_DIR / "api").mkdir(exist_ok=True)

    def generate_all(self, findings: List[Dict]) -> Dict:
        """Generate verification harnesses for all findings.

        Returns summary of generated artifacts.
        """
        results = {
            "total": len(findings),
            "certora_specs": 0,
            "fuzz_harnesses": 0,
            "api_tests": 0,
            "artifacts": [],
            "errors": [],
        }

        for finding in findings:
            bug_class = finding.get("bug_class", "")
            is_sc = finding.get("chain") or finding.get("contract_or_program")

            try:
                if is_sc:
                    # Smart contract finding → Certora + Fuzz
                    if bug_class in ("reentrancy", "access-control-bypass",
                                     "integer-overflow", "oracle-manipulation",
                                     "flash-loan-attack"):
                        spec = generate_certora_spec(finding)
                        fid = finding.get("finding_id", "unknown")[:8]
                        spec_path = VERIFY_DIR / "certora" / f"{fid}.spec"
                        spec_path.write_text(spec)
                        results["certora_specs"] += 1
                        results["artifacts"].append({
                            "type": "certora_spec",
                            "finding_id": fid,
                            "path": str(spec_path),
                        })

                    harness = generate_fuzz_harness(finding, "foundry")
                    fid = finding.get("finding_id", "unknown")[:8]
                    harness_path = VERIFY_DIR / "echidna" / f"{fid}Harness.sol"
                    harness_path.write_text(harness)
                    results["fuzz_harnesses"] += 1
                    results["artifacts"].append({
                        "type": "fuzz_harness",
                        "finding_id": fid,
                        "path": str(harness_path),
                    })

                else:
                    # Web/API finding
                    endpoint = finding.get("endpoint", "")
                    method = finding.get("method", "GET")
                    if endpoint and "/api" in endpoint:
                        test = generate_api_schema_test(endpoint, method, finding)
                        fid = finding.get("finding_id", "unknown")[:8]
                        test_path = VERIFY_DIR / "api" / f"{fid}_test.py"
                        test_path.write_text(test)
                        results["api_tests"] += 1
                        results["artifacts"].append({
                            "type": "api_schema_test",
                            "finding_id": fid,
                            "path": str(test_path),
                        })

            except Exception as e:
                results["errors"].append({
                    "finding_id": finding.get("finding_id", "?"),
                    "error": str(e),
                })

        return results

    def run_verification(self, artifact_path: str, artifact_type: str) -> Dict:
        """Execute a verification artifact."""
        if artifact_type == "certora_spec":
            # Need the contract path too
            return {"success": False, "error": "Contract path required for Certora"}
        elif artifact_type == "fuzz_harness":
            return run_echidna(artifact_path)
        else:
            return {"success": False, "error": f"Unknown artifact type: {artifact_type}"}


