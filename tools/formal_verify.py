def run_certora(spec_path: str, contract_path: str) -> Dict:
    """Run Certora Prover on a generated spec."""
    if not shutil.which("certoraRun"):
        return {"success": False, "error": "certoraRun not installed"}

    try:
        result = subprocess.run(
            ["certoraRun", contract_path,
             "--verify", f"{Path(contract_path).stem}:{spec_path}"],
            capture_output=True, text=True, timeout=600)

        # Parse Certora output
        output = result.stdout
        violations = "violated" in output.lower()
        passed = "successfully" in output.lower() and not violations

        return {
            "success": result.returncode == 0,
            "passed": passed,
            "violations_found": violations,
            "stdout": output[-2000:],
            "stderr": result.stderr[-500:],
        }
    except subprocess.TimeoutExpired:
        return {"success": False, "error": "Certora timeout (600s)"}
    except Exception as e:
        return {"success": False, "error": str(e)}


def run_echidna(harness_path: str) -> Dict:
    """Run Echidna fuzzer on a harness."""
    if not shutil.which("echidna"):
        return {"success": False, "error": "echidna not installed"}

    try:
        result = subprocess.run(
            ["echidna", harness_path, "--contract",
             Path(harness_path).stem],
            capture_output=True, text=True, timeout=600)

        # Parse Echidna output for invariant violations
        output = result.stdout + result.stderr
        violations = []
        for line in output.splitlines():
            if "violated" in line.lower() or "FAIL" in line:
                violations.append(line.strip())

        return {
            "success": result.returncode == 0,
            "violations": violations,
            "violations_count": len(violations),
            "output": output[-2000:],
        }
    except subprocess.TimeoutExpired:
        return {"success": False, "error": "Echidna timeout (600s)"}
    except Exception as e:
        return {"success": False, "error": str(e)}


