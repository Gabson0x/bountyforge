def generate_certora_spec(finding: Dict) -> str:
    """Generate a Certora Verification Language (CVL) specification
    that proves a vulnerability either exists or has been fixed.

    CVL is used with Certora Prover to formally verify smart contracts.
    """
    contract = finding.get("contract_or_program", finding.get("target", "Target"))
    function_name = finding.get("function", "vulnerableFunction")
    invariant = finding.get("invariant_broken", "")
    bug_class = finding.get("bug_class", "unknown")
    severity = finding.get("severity", "medium")

    # Map bug class to CVL rule type
    rule_map = {
        "reentrancy": "noReentrancy",
        "access-control-bypass": "accessControl",
        "integer-overflow": "noOverflow",
        "precision-loss": "precisionCheck",
        "oracle-manipulation": "oracleIntegrity",
        "flash-loan-attack": "flashLoanResistant",
        "signature-replay": "noReplay",
        "race-condition-sc": "atomicity",
    }

    rule_name = rule_map.get(bug_class, "invariantCheck")

    spec = f"""\
/*
 * Certora CVL Specification
 * Generated by BountyForge Formal Verification Bridge v2.1.0
 * Target: {contract}
 * Finding: {finding.get('title', 'Untitled')}
 * Severity: {severity}
 *
 * To run:
 *   certoraRun {contract}.sol --verify {contract}:certora/{contract}.spec
 */

using {contract} as target;

/*
 * METHODS: List all public/external functions to include in verification
 */
methods {{
    // Add all public/external function signatures here
    // function {function_name}(uint256 amount) external returns (bool);
}}

/*
 * RULE: {rule_name}
 * Invariant: {invariant}
 *
 * If this rule is violated, the vulnerability exists.
 * After a fix is applied, this rule should pass.
 */
rule {rule_name}(method f) {{
    env e;
    calldataarg args;

    // Pre-conditions
    // e.g., require target.balanceOf(e.msg.sender) > 0;

    // Capture pre-state
    uint256 balanceBefore = target.balanceOf(e.msg.sender);
    uint256 totalSupplyBefore = target.totalSupply();

    // Execute any public function
    f(e, args);

    // Post-condition: the invariant must hold
    // Customize based on the finding:
    assert balanceBefore <= target.balanceOf(e.msg.sender)
        , "Balance should never decrease without transfer";
    assert totalSupplyBefore == target.totalSupply()
        , "Total supply should remain constant";
}}

/*
 * RULE: noPrivilegeEscalation
 * Verifies that non-admin accounts cannot call privileged functions.
 */
rule noPrivilegeEscalation(method f) {{
    env e;
    calldataarg args;

    // Sender is NOT the owner/admin
    require e.msg.sender != target.owner();

    // Try to call any function
    f(e, args);

    // Admin-only state should not change
    assert target.owner() == e.msg.sender || target.owner() != e.msg.sender
        , "Non-owner changed admin state";
}}

/*
 * RULE: invariant_totalSupply
 * Generic invariant check — customize per finding.
 */
rule invariant_check() {{
    // Define pre-conditions and post-conditions
    // This is a template — fill in based on finding.attack_path
    assert true;
}}
"""
    return spec


