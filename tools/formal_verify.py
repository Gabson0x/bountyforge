def generate_api_schema_test(endpoint: str, method: str,
                              finding: Dict) -> str:
    """Generate a schemathesis-compatible test for API findings.

    Schemathesis auto-generates test cases from OpenAPI schemas.
    This generates a targeted test for a specific finding.
    """
    return f"""\
# API Schema Fuzz Test
# Generated by BountyForge v2.1.0
# Target: {method} {endpoint}
# Finding: {finding.get('title', 'Untitled')}
#
# Run with:
#   schemathesis run --base-url={endpoint.split('/api')[0]} \\
#       -A '{finding.get('parameter', '')}' \\
#       --hypothesis-max-examples=1000

import schemathesis
import pytest

schema = schemathesis.from_uri("{endpoint.split('/api')[0]}/openapi.json")

@schema.parametrize()
def test_api_invariant(case):
    \"\"\"Test that the API maintains security invariants.\"\"\"
    response = case.call()

    # Check 1: No information disclosure
    assert "password" not in response.text.lower()
    assert "secret" not in response.text.lower()
    assert "token" not in response.text.lower()

    # Check 2: Auth required for sensitive endpoints
    if "/admin" in case.operation.path or "/internal" in case.operation.path:
        assert response.status_code in (401, 403), \\
            f"Admin endpoint returned {{response.status_code}}"

    # Check 3: No mass assignment
    if case.operation.method in ("POST", "PUT", "PATCH"):
        response = case.call(extra_headers={{"X-Test-Role": "admin"}})
        if response.status_code == 200:
            # Verify role header wasn't actually applied
            pass
"""
    return ""


