def generate_fuzz_harness(finding: Dict, framework: str = "foundry") -> str:
    """Generate a fuzzing harness that tries to break the invariant.

    Supports Foundry (Echidna-compatible) and Medusa format.
    """
    contract = finding.get("contract_or_program", finding.get("target", "Target"))
    invariant = finding.get("invariant_broken", "")
    bug_class = finding.get("bug_class", "unknown")
    title = finding.get("title", "Finding").replace(" ", "")

    if framework == "foundry":
        harness = f"""\
// SPDX-License-Identifier: UNLICENSED
pragma solidity ^0.8.19;

import "../src/{contract}.sol";

/// @title Fuzz Harness: {title}
/// @notice Proves or disproves: {invariant}
/// @custom:generated BountyForge Formal Verification Bridge v2.1.0
///
/// Run with:
///   echidna {title}Harness.sol --contract {title}Harness --config echidna.yaml
///   medusa fuzz --target contracts/harness/{title}Harness.sol

contract {title}Harness {{
    {contract} target;

    constructor() {{
        target = new {contract}();
    }}

    // ================================================================
    // Helper functions — call any target function
    // ================================================================

    function callTarget(bytes memory data) public returns (bool) {{
        (bool success, ) = address(target).call(data);
        return success;
    }}

    // ================================================================
    // Invariants to check (Echidna/Medusa will call these)
    // Functions starting with "echidna_" or "invariant_" are assertions
    // ================================================================

    /// @custom:invariant {invariant}
    function echidna_invariant() public view returns (bool) {{
        // TODO: Encode the invariant as a boolean check
        // Example: return target.totalSupply() <= target.MAX_SUPPLY();
        return true;
    }}

    /// @custom:invariant No unauthorized role changes
    function echidna_noPrivilegeEscalation() public view returns (bool) {{
        // TODO: Check that admin/owner hasn't changed unexpectedly
        return true;
    }}

    /// @custom:invariant Balances sum to totalSupply
    function echidna_balanceSum() public view returns (bool) {{
        // TODO: sum of all balances == totalSupply
        return true;
    }}
}}
"""
    elif framework == "medusa":
        harness = f"""\
# Medusa Fuzzing Configuration
# Generated by BountyForge v2.1.0
# Target: {contract}
# Finding: {title}

fuzzing:
  workers: 4
  testLimit: 50000
  callSequenceLength: 100
  shrinkLimit: 5000
  coverage: true

  # Corpus directory for interesting inputs
  corpusDirectory: medusa-corpus-{title.lower()}

  # Deployer address (has initial balance)
  deployer: "0x30000"
  senderAddresses:
    - "0x10000"
    - "0x20000"
    - "0x30000"

sequences:
  # Custom sequence that targets the vulnerable function
  - name: "exploit_{bug_class}"
    calls:
      - target.function_{bug_class}()
      - wait: 1
      - target.function_{bug_class}()
"""
    else:
        harness = f"// Unknown framework: {framework}"

    return harness


